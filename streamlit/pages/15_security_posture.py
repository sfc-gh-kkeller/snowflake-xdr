import streamlit as st
import pandas as pd
import json
from utils.deprecation import show_deprecation_banner

st.set_page_config(page_title="Security Posture", layout="wide")
show_deprecation_banner("security_posture")
st.title("Security Posture")
st.caption("Executive view: coverage, response, and AI-generated reporting")

conn = st.connection("snowflake")

m = conn.query("SELECT * FROM SNOWFLAKE_XDR.DETECTIONS.V_POSTURE_METRICS").iloc[0]

col1, col2, col3, col4 = st.columns(4)
with col1:
    st.metric("Open Incidents", int(m["OPEN_INCIDENTS"]))
with col2:
    st.metric("Untriaged Findings", int(m["UNTRIAGED_FINDINGS"]))
with col3:
    st.metric("MTTR (min)", round(m["MTTR_MINUTES"], 0))
with col4:
    st.metric("Active IOCs", int(m["ACTIVE_IOCS"]))

col5, col6, col7, col8 = st.columns(4)
with col5:
    st.metric("Enabled Rules", int(m["ENABLED_RULES"]))
with col6:
    cov = f'{int(m["TACTICS_COVERED"])}/{int(m["TOTAL_TACTICS"])}'
    st.metric("MITRE Tactics Covered", cov)
with col7:
    st.metric("Findings (7d)", int(m["FINDINGS_7D"]))
with col8:
    st.metric("Critical/High (7d)", int(m["CRITICAL_7D"]))

st.markdown("---")

left, right = st.columns(2)
with left:
    st.subheader("MITRE ATT&CK Coverage")
    coverage = conn.query("""
        SELECT tactic_id, tactic_name,
               COUNT(DISTINCT technique_id) as techniques_total,
               COUNT(DISTINCT IIF(enabled, technique_id, NULL)) as techniques_enabled
        FROM SNOWFLAKE_XDR.REFERENCE.MITRE_TECHNIQUES
        GROUP BY 1, 2 ORDER BY 1
    """)
    rules_by_tactic = conn.query("""
        SELECT mitre_tactic_id as tactic_id, COUNT(DISTINCT rule_id) as rules
        FROM SNOWFLAKE_XDR.DETECTIONS.DETECTION_RULES
        WHERE enabled = TRUE AND mitre_tactic_id IS NOT NULL
        GROUP BY 1
    """)
    if not coverage.empty:
        cov = coverage.merge(rules_by_tactic, on="TACTIC_ID", how="left").fillna({"RULES": 0})
        st.dataframe(
            cov[["TACTIC_ID", "TACTIC_NAME", "TECHNIQUES_ENABLED", "RULES"]]
               .rename(columns={
                   "TACTIC_ID": "Tactic", "TACTIC_NAME": "Name",
                   "TECHNIQUES_ENABLED": "Techniques with Detection", "RULES": "Enabled Rules"
               }),
            use_container_width=True, hide_index=True,
        )

with right:
    st.subheader("Response Automation Health")
    pa = conn.query("""
        SELECT action_type, COUNT(*) as executed,
               SUM(IFF(status = 'success', 1, 0)) as succeeded
        FROM SNOWFLAKE_XDR.RESPONSE.PLAYBOOK_ACTIONS
        GROUP BY 1 ORDER BY 2 DESC
    """)
    if not pa.empty:
        st.dataframe(
            pa.rename(columns={
                "ACTION_TYPE": "Action Type", "EXECUTED": "Executed", "SUCCEEDED": "Succeeded"
            }),
            use_container_width=True, hide_index=True,
        )
    else:
        st.info("No playbook actions executed yet.")

st.markdown("---")

st.subheader("AI Executive Report")
st.caption("Generated by Cortex AI from live platform metrics")
if st.button("Generate Executive Report", type="primary"):
    with st.spinner("Cortex AI is drafting the executive report..."):
        try:
            r = conn.query(
                "CALL SNOWFLAKE_XDR.DETECTIONS.AI_EXEC_REPORT()",
                ttl=0,
            )
            report = json.loads(r.iloc[0][0])["report"]
            st.markdown(report)
        except Exception as e:
            st.error(f"Report generation failed: {e}")
else:
    st.info("Click to generate a CISO-ready security report from live data.")
